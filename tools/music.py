"""Makes the intro's background music from code: a light marimba-and-bass loop that repeats seamlessly.
Run: python3 tools/music.py   -> audio/music.mp3 (and its tempo, for cutting on the beat, in js/music.js)"""
import json, os, subprocess, tempfile
import numpy as np, soundfile as sf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SR = 44100; BPM = 96; BEAT = 60 / BPM; BARS = 8; LEN = int(SR * BEAT * 4 * BARS)
rng = np.random.default_rng(3)
out = np.zeros((LEN + SR * 3, 2))

def note(m): return 440 * 2 ** ((m - 69) / 12)
def add(sig, t, pan=0.0, gain=1.0):
    i = int(t * SR); n = len(sig)
    l, r = np.cos((pan + 1) * np.pi / 4), np.sin((pan + 1) * np.pi / 4)
    out[i:i + n, 0] += sig * gain * l; out[i:i + n, 1] += sig * gain * r

def marimba(f, dur=1.1):
    t = np.arange(int(SR * dur)) / SR
    env = np.exp(-t * 6.5) * (1 - np.exp(-t * 900))
    s = np.sin(2 * np.pi * f * t) + 0.32 * np.sin(2 * np.pi * f * 3.93 * t) * np.exp(-t * 18) + 0.12 * np.sin(2 * np.pi * f * 9.2 * t) * np.exp(-t * 40)
    return s * env
def bass(f, dur):
    t = np.arange(int(SR * dur)) / SR
    env = np.minimum(1, t * 60) * np.exp(-t * 2.2)
    s = np.sin(2 * np.pi * f * t) + 0.25 * np.sin(4 * np.pi * f * t)
    return s * env
def shaker(dur=0.09):
    n = int(SR * dur); t = np.arange(n) / SR
    w = rng.standard_normal(n); w = np.diff(np.concatenate([[0], w]))  # brighten
    return w * np.exp(-t * 55) * np.minimum(1, t * 400)
def pluck_bell(f, dur=1.6):
    t = np.arange(int(SR * dur)) / SR
    return (np.sin(2 * np.pi * f * t) * 0.8 + 0.2 * np.sin(2 * np.pi * f * 2.76 * t) * np.exp(-t * 6)) * np.exp(-t * 3) * np.minimum(1, t * 500)

# F major: F  Dm  Bb  C  |  F  Am  Bb  C
CH = [(53, [65, 69, 72]), (50, [62, 65, 69]), (46, [58, 62, 65]), (48, [60, 64, 67]),
      (53, [65, 69, 72]), (45, [57, 60, 64]), (46, [58, 62, 65]), (48, [60, 64, 67, 70])]
ARP = [0, 1, 2, 1, 0, 2, 1, 2]           # eighth-note pattern within each bar
MEL = [(0, 77), (1.5, 76), (2, 74), (3, 72), (4, 74), (6, 72), (6.5, 69), (8, 70), (10, 72), (12, 74), (13.5, 72), (14, 69), (15, 67),
       (16, 77), (17.5, 79), (18, 81), (19, 77), (20, 76), (22, 72), (24, 74), (25, 72), (26, 70), (28, 72), (30, 67)]  # in beats

for b, (root, tones) in enumerate(CH):
    t0 = b * 4 * BEAT
    add(bass(note(root - 12), BEAT * 1.9), t0, 0, 0.42); add(bass(note(root - 12), BEAT * 1.4), t0 + 2.5 * BEAT, 0, 0.3)
    for i, k in enumerate(ARP):
        f = note(tones[k % len(tones)]); sw = (0.03 if i % 2 else 0) * BEAT   # a little swing so it isn't mechanical
        add(marimba(f), t0 + i * BEAT / 2 + sw, -0.35 + 0.1 * (i % 3), 0.17 * (1.0 if i % 2 == 0 else 0.8))
    for i in range(8):
        add(shaker(), t0 + i * BEAT / 2 + (0.025 if i % 2 else 0), 0.45, 0.05 if i % 2 else 0.032)
for beat, m in MEL:
    add(pluck_bell(note(m)), beat * BEAT, 0.25, 0.075)

# wrap the tail past the loop point back onto the start, so the loop is seamless
tail = out[LEN:]; out[:len(tail)] += tail; out = out[:LEN]
out /= np.max(np.abs(out)) / 0.6
with tempfile.TemporaryDirectory() as d:
    sf.write(f'{d}/m.wav', out, SR)
    os.makedirs(f'{ROOT}/audio', exist_ok=True)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', f'{d}/m.wav', '-c:a', 'libmp3lame', '-b:a', '96k', f'{ROOT}/audio/music.mp3'], check=True)
open(f'{ROOT}/js/music.js', 'w').write('/* Generated by tools/music.py. */\nwindow.MUSIC=' + json.dumps({'bpm': BPM, 'loop': round(LEN / SR, 4)}) + ';\n')
print('loop', LEN / SR, 's')
