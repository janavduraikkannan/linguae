"""Builds the intro's voice track from ElevenLabs takes (one per line of tools/script.json).

For every line: the ElevenLabs mp3 is trimmed and loudness-matched, Rhubarb Lip Sync works out the mouth shapes,
and the result goes to audio/<id>.mp3 plus js/voice.js (durations, captions, word timings, mouth cues).
The voices and prompts used are recorded in tools/elevenlabs.json.

Needs: ffmpeg, numpy, soundfile, Rhubarb Lip Sync 1.13.
Run:  python3 tools/import_voices.py /path/to/mp3-dir /path/to/rhubarb [only-this-id]
"""
import json, os, subprocess, sys, tempfile
import numpy as np, soundfile as sf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
SRC = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/work/el/mp3'
RHUBARB = sys.argv[2] if len(sys.argv) > 2 else '/home/claude/tts/Rhubarb-Lip-Sync-1.13.0-Linux/rhubarb'
ONLY = sys.argv[3] if len(sys.argv) > 3 else None
SR = 22050
S = json.load(open(f'{ROOT}/tools/script.json'))

# Shared text helpers (same as the older Kokoro pipeline, kept here so this script has no TTS dependency).
import re, html
SEG = re.compile(r'\{([a-z-]+):([^}|]+)(?:\|([^}]*))?\}')

def caption_html(text):
    h = ''; pos = 0
    for m in SEG.finditer(text):
        h += html.escape(text[pos:m.start()])
        w, g = m.group(2), m.group(3)
        h += f'<u data-en="{html.escape(g)}">{html.escape(w)}</u>' if g else f'<i>{html.escape(w)}</i>'
        pos = m.end()
    return h + html.escape(text[pos:])

def word_times(text, cues, dur):
    plain = SEG.sub(lambda m: m.group(2), text)
    words = plain.split()
    speech = []
    for i, (t, v) in enumerate(cues):
        end = cues[i + 1][0] if i + 1 < len(cues) else dur
        if v != 'X': speech.append((t, end))
    merged = []
    for a, b in speech:
        if merged and a - merged[-1][1] < 0.12: merged[-1] = (merged[-1][0], b)
        else: merged.append((a, b))
    total = sum(b - a for a, b in merged) or dur
    weights = [len(re.sub(r'\W', '', w)) + 1.5 for w in words]; W = sum(weights)
    out, acc = [], 0.0
    def at(x):
        for a, b in merged:
            if x <= b - a: return a + x
            x -= b - a
        return dur
    for w in weights:
        out.append(round(at(acc / W * total), 3)); acc += w
    return out

def lipsync(wav, text, english):
    with tempfile.NamedTemporaryFile('w', suffix='.txt', delete=False) as f:
        f.write(text); dlg = f.name
    cmd = [RHUBARB, '-q', '-f', 'json', '--extendedShapes', 'GHX', '-r', 'pocketSphinx' if english else 'phonetic', wav]
    if english: cmd[1:1] = ['-d', dlg]
    r = subprocess.run(cmd, capture_output=True, text=True, check=True)
    return [[round(c['start'], 3), c['value']] for c in json.loads(r.stdout)['mouthCues']]

def trim(a, thr=0.01):
    idx = np.where(np.abs(a) > thr)[0]
    if not len(idx): return a
    return a[max(0, idx[0] - int(0.03 * SR)): idx[-1] + int(0.08 * SR)]

def main():
    vf = f'{ROOT}/js/voice.js'
    data = {}
    if os.path.exists(vf):
        try: data = json.loads(open(vf).read().split('=', 1)[1].rstrip().rstrip(';'))
        except Exception: data = {}
    for lid, (who, text) in S['lines'].items():
        if ONLY and lid != ONLY: continue
        src = f'{SRC}/{lid}.mp3'
        if not os.path.exists(src): print('MISSING', lid); continue
        with tempfile.TemporaryDirectory() as d:
            raw, cut, wav = f'{d}/raw.wav', f'{d}/cut.wav', f'{d}/out.wav'
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src, '-ar', str(SR), '-ac', '1', raw], check=True)
            a, _ = sf.read(raw, dtype='float32'); sf.write(cut, trim(a), SR)
            af = 'highpass=f=70,acompressor=threshold=-18dB:ratio=2.5:attack=5:release=80,loudnorm=I=-16:TP=-1.5:LRA=7'
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', cut, '-af', af, '-ar', str(SR), '-ac', '1', wav], check=True)
            dur = sf.info(wav).duration
            english = not SEG.search(text)
            plain = SEG.sub(lambda m: m.group(2), text)
            try: cues = lipsync(wav, plain, english)
            except subprocess.CalledProcessError: cues = lipsync(wav, plain, False)
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', wav, '-c:a', 'libmp3lame', '-b:a', '64k', f'{ROOT}/audio/{lid}.mp3'], check=True)
        data[lid] = {'who': who, 'dur': round(dur, 3), 'cap': caption_html(text), 'words': word_times(text, cues, dur), 'cues': cues}
        print(f'{lid:12s} {who:11s} {dur:5.2f}s {len(cues):3d} cues')
    data = {k: data[k] for k in S['lines'] if k in data}
    open(vf, 'w').write('/* Generated by tools/import_voices.py from tools/script.json and the ElevenLabs takes. */\nwindow.VOICE=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')

if __name__ == '__main__':
    main()
