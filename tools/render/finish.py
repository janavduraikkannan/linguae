"""Turns render.js output into the site's intro videos.

For each part: the final MP4 (H.264 + AAC, ready to stream), a silent back-and-forth loop of the last moment for
parts that end on a question, and js/intro-videos.js, which tells the player where the voice lines, the question,
the background changes and the ending are.
usage: python3 tools/render/finish.py <render out dir containing desktop/ and phone/> [crf]
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1]
CRF = sys.argv[2] if len(sys.argv) > 2 else '24'
SIZES = {'desktop': (1440, 720), 'phone': (390, 540)}
HOLD = 1.4  # seconds of the end used for the question loop

def run(*a): subprocess.run(a, check=True)

def encode(video, pcm, out):
    args = ['ffmpeg', '-v', 'error', '-y', '-i', video]
    if pcm: args += ['-f', 's16le', '-ar', '44100', '-ac', '1', '-i', pcm]
    args += ['-map', '0:v'] + (['-map', '1:a', '-c:a', 'aac', '-b:a', '96k', '-ac', '1'] if pcm else ['-an'])
    args += ['-c:v', 'libx264', '-preset', 'slow', '-tune', 'animation', '-crf', CRF, '-pix_fmt', 'yuv420p',
             '-profile:v', 'high', '-level', '4.1', '-g', '60', '-movflags', '+faststart', '-shortest', out]
    run(*args)

manifest = {}
for ver, (w, h) in SIZES.items():
    d = os.path.join(SRC, ver)
    if not os.path.isdir(d): continue
    outd = os.path.join(ROOT, 'video', ver); os.makedirs(outd, exist_ok=True)
    segs = {}
    for f in sorted(os.listdir(d)):
        if not f.endswith('.json'): continue
        name = f[:-5]; info = json.load(open(os.path.join(d, f)))
        v = os.path.join(d, name + '.video.mp4'); pcm = os.path.join(d, name + '.pcm')
        encode(v, pcm, os.path.join(outd, name + '.mp4'))
        info['hold'] = bool(info.get('ask'))
        if info['hold']:
            start = max(0, info['dur'] - HOLD)
            run('ffmpeg', '-v', 'error', '-y', '-ss', f'{start:.3f}', '-i', v, '-filter_complex', '[0:v]split[a][b];[b]reverse[r];[r][a]concat=n=2:v=1[v]',
                '-map', '[v]', '-an', '-c:v', 'libx264', '-preset', 'slow', '-tune', 'animation', '-crf', CRF, '-pix_fmt', 'yuv420p',
                '-profile:v', 'high', '-level', '4.1', '-movflags', '+faststart', os.path.join(outd, name + '-hold.mp4'))
        for k in ('frames',): info.pop(k, None)
        segs[name] = info
        print(ver, name, f"{info['dur']:.1f}s", f"{os.path.getsize(os.path.join(outd, name + '.mp4')) / 1e6:.1f} MB")
    manifest[ver] = {'w': w, 'h': h, 'segs': segs}

old = {}
p = os.path.join(ROOT, 'js', 'intro-videos.js')
if os.path.exists(p):
    try: old = json.loads(open(p).read().split('=', 1)[1].rstrip().rstrip(';'))
    except Exception: old = {}
old.update(manifest)
open(p, 'w').write('/* Generated by tools/render/finish.py: the intro\'s video parts, and when things happen in each. */\nwindow.INTRO_VIDEOS=' + json.dumps(old, ensure_ascii=False, separators=(',', ':')) + ';\n')
